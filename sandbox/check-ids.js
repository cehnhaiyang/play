const fs = require('fs');
const md = fs.readFileSync('models-ids.md', 'utf8');
const lines = md.split('\n');
const rows = lines.filter(l => /^[0-9a-f-]{36} \| /.test(l));
const ids = rows.map(l => l.split(' | ')[0].trim());
const uniq = new Set(ids);
const bad = ids.filter(i => !/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/.test(i));
console.log(JSON.stringify({bytes: Buffer.byteLength(md), totalLines: lines.length, idRows: rows.length, uniqueIds: uniq.size, malformed: bad.length, first: ids[0], last: ids[ids.length-1], head: lines.slice(0,8)}));
fs.writeFileSync('models-ids.txt', [...uniq].join('\n') + '\n');
console.log('txt bytes', fs.statSync('models-ids.txt').size);
